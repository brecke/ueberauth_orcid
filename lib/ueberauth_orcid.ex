defmodule UeberauthOrcid do
  @moduledoc """
  ORCID authentication for Ueberauth.

  Configure `Ueberauth.Strategy.Orcid` as the provider and
  `Ueberauth.Strategy.Orcid.OAuth` with the ORCID application's credentials.
  See the [setup guide](readme.html) for runtime configuration, host pipelines
  and callback handling, and the [changelog](changelog.html) before upgrading.
  Returned credentials and raw tokens are sensitive. This library authenticates
  an ORCID identity; account creation, linking and sessions belong to the host.
  """
end
